def _group_signature(group: dict, signatures: tuple[str, ...]) -> str | None:
    """Return the FIRST signature in ``signatures`` matched by any command in ``group``, else None."""
    for hook in group.get("hooks", []):
        command = hook.get("command", "")
        for sig in signatures:
            if sig in command:
                return sig
    return None


def merge_settings(
    existing: dict,
    harness_signatures: tuple[str, ...] = HARNESS_SIGNATURES,
    harness_groups: dict[str, list[dict]] = HARNESS_HOOK_GROUPS,
    retired_signatures: tuple[str, ...] = RETIRED_SIGNATURES,
) -> dict:
    """Merge the harness hook groups into ``existing`` settings IN PLACE, order-preserving (Regime B-json).

    For each event in ``harness_groups`` the desired harness group (identified by its command
    signature) is APPENDED-OR-REPLACED where it already appears — never duplicated, never sorted,
    never moved. GSD/human groups (no harness signature) are kept verbatim in their live position;
    a second harness group matching an already-placed signature is DROPPED (de-dup → no double-wire).
    A harness group absent from ``existing`` is appended at the tail of its event list. A group
    matching a ``retired_signatures`` entry is DROPPED outright — it is a formerly harness-owned
    group whose signature was deliberately removed (a deletion phase), not a GSD/human group.

    Because the Phase 2/4 hooks are ALREADY committed in the live order, calling this on the parsed
    live ``.claude/settings.json`` reproduces it byte-for-byte from the FIRST emit (serialize with
    ``json.dumps(merged, indent=2, ensure_ascii=False) + "\\n"`` — NO ``sort_keys``). The input is
    not mutated; a deep copy is returned.
    """
    merged = copy.deepcopy(existing)
    hooks = merged.setdefault("hooks", {})

    for event, desired_groups in harness_groups.items():
        existing_groups = hooks.get(event, [])
        # Map each desired harness group to the signature it carries, preserving authored order.
        desired_by_sig: dict[str, dict] = {}
        desired_order: list[str] = []
        for group in desired_groups:
            sig = _group_signature(group, harness_signatures)
            if sig is None:  # pragma: no cover — HARNESS_HOOK_GROUPS always carries a signature
                continue
            desired_by_sig[sig] = group
            desired_order.append(sig)

        result: list[dict] = []
        placed: set[str] = set()
        for group in existing_groups:
            sig = _group_signature(group, harness_signatures)
            if sig is None:
                if _group_signature(group, retired_signatures) is not None:
                    # A retired harness group — drop it, this is the deletion path (D-12).
                    continue
                # GSD/human group — keep verbatim, in place, never removed/reordered (T-07-02).
                result.append(group)
            elif sig in desired_by_sig:
                if sig not in placed:
                    # Replace the harness group in place with the canonical definition.
                    result.append(copy.deepcopy(desired_by_sig[sig]))
                    placed.add(sig)
                # else: a duplicate harness group — DROP it (de-dup, no double-wire / Pitfall 4).
            else:
                # A harness-signature group we don't own the canonical form of — keep verbatim.
                result.append(group)

        # Append any desired harness group not already present (first-time wiring at the tail).
        for sig in desired_order:
            if sig not in placed:
                result.append(copy.deepcopy(desired_by_sig[sig]))
                placed.add(sig)

        # Only touch the event list if the harness actually owns groups there (keeps the key in its
        # live insertion position — reassigning an existing key never moves it).
        if event in hooks or result:
            hooks[event] = result

    return merged
